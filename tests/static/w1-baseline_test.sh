#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-2.0-only
#
# Compare the warnings of a W=1 build against the recorded baseline.
#
#   w1-baseline_test.sh <w1.log> <kernel-release>              check
#   w1-baseline_test.sh --generate <w1.log> <kernel-release>   write baseline
#
# The baseline holds the warnings that the *unmodified* upstream hptiop.c
# produces for that kernel, so inherited upstream warnings are tolerated but
# any warning introduced by this tree fails the check. Warnings are
# normalised to "file:function:flag:message" (line numbers stripped) so that
# moving code around does not invalidate the baseline.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
mode=check
if [[ ${1:-} == --generate ]]; then
	mode=generate
	shift
fi
log=${1:?usage: w1-baseline_test.sh [--generate] <w1.log> <kernel-release>}
krel=${2:?kernel release required}

case $krel in
6.8.*) target=u2404-6.8 ;;
7.0.*) target=u2604-7.0 ;;
*)
	echo "w1-baseline: no baseline for unsupported kernel $krel" >&2
	exit 2
	;;
esac
baseline=$ROOT/tests/static/w1-baseline/$target.txt

normalise() {
	perl -ne '
		if (/In function .(\w+)/) { $fn = $1; next; }
		if (/^WARNING: modpost: (.*)$/) { print "modpost:-:-:$1\n"; next; }
		next unless /: (warning|error): /;
		next if /the compiler differs from the one used to build the kernel/;
		my ($file, $msg) = m{^(?:.*/)?([^/:]+):\d+:\d+: (.*)$} or next;
		my $flag = ($msg =~ s/\s*\[(-W[^\]]+)\]$//) ? $1 : "-";
		print join(":", $file, $fn // "-", $flag, $msg), "\n";
	' "$1" | sort -u
}

current=$(normalise "$log")

if [[ $mode == generate ]]; then
	{
		echo "# W=1 warnings of unmodified upstream hptiop for $target ($krel)."
		echo "# Generated by: make w1-baseline. One normalised warning per line."
		[[ -n $current ]] && printf '%s\n' "$current"
	} > "$baseline"
	echo "w1-baseline: wrote $baseline ($(grep -vc '^#' "$baseline" || true) warnings)"
	exit 0
fi

if [[ ! -f $baseline ]]; then
	echo "w1-baseline: missing $baseline (run make w1-baseline)" >&2
	exit 1
fi

if grep -q ': error: ' "$log"; then
	echo "w1-baseline: build errors in $log" >&2
	exit 1
fi

known=$(grep -v '^#' "$baseline" || true)
new=$(comm -23 <(printf '%s\n' "$current" | sed '/^$/d') \
	<(printf '%s\n' "$known" | sed '/^$/d'))

if [[ -n $new ]]; then
	echo "w1-baseline: new W=1 warnings for $target:" >&2
	printf '  %s\n' "$new" >&2
	exit 1
fi
echo "w1-baseline: OK ($target, $(printf '%s' "$current" | grep -c . || true) inherited warnings)"
